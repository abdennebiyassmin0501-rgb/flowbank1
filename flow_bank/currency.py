"""currency.py — تحويل مبالغ بيانات الأفراد من الدولار التايواني (NT$) إلى الدينار الجزائري (DA)."""

# بيانات الأفراد بالدولار التايواني (NT$). نعرض المبالغ بالدينار الجزائري (DA) بهذا السعر.
# سعر متوسط السوق من wise.com بتاريخ 24 أكتوبر 2026. غيّريه هنا إن أردتِ سعرًا آخر.
DA_PER_NTD = 4.135
RATE_NOTE = "المبالغ محوّلة من الدولار التايواني بسعر \u20661 NT$ = 4.135 DA\u2069 (سعر أكتوبر 2026)، وهي أصلًا مبالغ تايوانية من سنة 2005."


def to_da(v_ntd):
    return v_ntd * DA_PER_NTD


def to_ntd(v_da):
    return v_da / DA_PER_NTD
